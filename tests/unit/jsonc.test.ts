// JSONC (Windows Terminal's settings.json): parsed with places, one string set with nothing else in
// the file changed, comments and trailing commas kept, bad files refused with their line.

import { describe, test } from 'node:test'
import assert from 'node:assert/strict'
import { find, findString, JsoncError, parse, setString } from '../../app/jsonc.ts'

const WT = `// This file was initially generated by Windows Terminal
{
    "$help": "https://aka.ms/terminal-documentation",
    /* the profiles */
    "profiles":
    {
        "defaults":
        {
            // my font
            "font":
            {
                "face": "Consolas",
                "size": 12,
            },
        },
        "list": [ { "guid": "{a}", "name": "Ubuntu" } ]
    },
}
`

describe('jsonc', () => {
  test('parses comments, trailing commas, escapes, numbers and a byte order mark', () => {
    const root = parse(WT)
    assert.equal(findString(root, ['profiles', 'defaults', 'font', 'face']), 'Consolas')
    assert.deepEqual(find(root, ['profiles', 'defaults', 'font', 'size']), { type: 'other', start: WT.indexOf('12'), end: WT.indexOf('12') + 2, value: 12 })
    assert.equal(findString(root, ['profiles', 'list', 0, 'name']), 'Ubuntu')
    assert.equal(find(root, ['profiles', 'list', 1]), undefined)
    assert.equal(find(root, ['profiles', 'defaults', 0]), undefined)
    assert.equal(find(root, ['nope', 'deeper']), undefined)
    const r = parse('﻿{"a": "x\\"y\\u00e9\\n\\/", "b": [true, false, null, -1.5e3], "c": {}}')
    assert.equal(findString(r, ['a']), 'x"yé\n/')
    assert.deepEqual((find(r, ['b']) as any).items.map((n: any) => n.value), [true, false, null, -1500])
  })

  test('refuses what isn\'t JSONC, saying on which line', () => {
    const bad: [string, RegExp][] = [
      ['{\n"a": 1\n"b": 2}', /expected , or \} \(line 3\)/],
      ['{"a" 1}', /expected : after a key/],
      ['{a: 1}', /expected a key in quotes/],
      ['[1 2]', /expected , or \]/],
      ['{"a": "x', /a string that never ends/],
      ['{"a": "x\ny"}', /a line break inside a string/],
      ['{"a": "\\q"}', /a bad escape/],
      ['{"a": 1} /* open', /a \/\* comment that never ends/],
      ['{"a": ', /the file ends too soon/],
      ['{"a": nope}', /unexpected “n”/],
      ['{} {}', /more after the end/],
    ]
    for (const [text, why] of bad) assert.throws(() => parse(text), (e: unknown) => e instanceof JsoncError && why.test(e.message), text)
    assert.equal(((): number => { try { parse('{\n\n  x') } catch (e) { return (e as JsoncError).line } return 0 })(), 3)
  })

  test('sets a string in place: only its characters change', () => {
    const out = setString(WT, ['profiles', 'defaults', 'font', 'face'], 'Cascadia Mono NF, Courier New')
    assert.equal(out, WT.replace('"Consolas"', '"Cascadia Mono NF, Courier New"'))
    // A key given twice: the last one counts, as in JSON.parse.
    assert.equal(setString('{"a": "1", "a": "2"}', ['a'], 'x'), '{"a": "1", "a": "x"}')
    // From a base path (a profile in the list).
    assert.equal(setString(WT, ['name'], 'Mine', ['profiles', 'list', 0]), WT.replace('"Ubuntu"', '"Mine"'))
  })

  test('makes the keys that are missing, indented as the file is, comments kept', () => {
    // No face in font: on its own line before "size".
    const noFace = WT.replace('"face": "Consolas",\n                ', '')
    assert.equal(setString(noFace, ['profiles', 'defaults', 'font', 'face'], 'F'), WT.replace('"Consolas"', '"F"'))
    // No font at all: a font object before the first key of defaults, after the comment.
    const noFont = `{\r\n  "profiles": {\r\n    "defaults": {\r\n      // keep me\r\n      "opacity": 90\r\n    }\r\n  }\r\n}\r\n`
    assert.equal(
      setString(noFont, ['profiles', 'defaults', 'font', 'face'], 'F'),
      `{\r\n  "profiles": {\r\n    "defaults": {\r\n      // keep me\r\n      "font": {\r\n        "face": "F"\r\n      },\r\n      "opacity": 90\r\n    }\r\n  }\r\n}\r\n`,
    )
    // Empty defaults, and none.
    assert.equal(setString('{\n\t"profiles": {\n\t\t"defaults": {}\n\t}\n}', ['profiles', 'defaults', 'font', 'face'], 'F'), '{\n\t"profiles": {\n\t\t"defaults": {\n\t\t\t"font": {\n\t\t\t\t"face": "F"\n\t\t\t}\n\t\t}\n\t}\n}')
    assert.equal(setString('{\n    "profiles": {\n        "list": []\n    }\n}', ['defaults', 'font', 'face'], 'F', ['profiles']), '{\n    "profiles": {\n        "defaults": {\n            "font": {\n                "face": "F"\n            }\n        },\n        "list": []\n    }\n}')
    // An empty object with a comment in it: the comment stays, after the new key.
    assert.equal(setString('{\n  "a": { /* none yet */ }\n}', ['a', 'b'], 'F'), '{\n  "a": {\n    "b": "F" /* none yet */ }\n}')
    // On one line: inserted on that line.
    assert.equal(setString('{"profiles": {"defaults": {"opacity": 90}}}', ['profiles', 'defaults', 'font', 'face'], 'F'), '{"profiles": {"defaults": {"font": { "face": "F" }, "opacity": 90}}}')
    assert.equal(setString('{"x": 1}', ['a', 'b', 'c'], 'F'), '{"a": { "b": { "c": "F" } }, "x": 1}')
    // A file with no indent at all: four spaces.
    assert.equal(setString('{}', ['a'], 'F'), '{\n    "a": "F"\n}')
  })

  test('refuses to set through something that is not an object', () => {
    assert.throws(() => setString('{"profiles": []}', ['profiles', 'defaults'], 'F'), /profiles is not an object/)
    assert.throws(() => setString('{"a": {"b": {}}}', ['a', 'b'], 'F'), /a\.b is not a string/)
    assert.throws(() => setString('[]', ['a'], 'F'), /the file is not an object/)
    assert.throws(() => setString('{"p": 1}', ['a'], 'F', ['p']), /p is not an object/)
  })
})
